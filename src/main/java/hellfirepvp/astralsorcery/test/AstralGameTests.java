    /**
     * Verifies that {@code WorldNetworkHandler.addLink()} refuses links once a
     * source node has reached its {@code maxNodeConnections} limit.
     *
     * <p>Registers a source and {@code maxConn+2} receivers directly in the
     * handler (no block entities required) then counts successful links.</p>
     */
    @GameTest(template = PLATFORM)
    public void testStarlightNetworkMaxConnectionsEnforced(GameTestHelper helper) {
        ServerLevel level = helper.getLevel();
        WorldNetworkHandler handler = WorldNetworkHandler.getOrCreate(level);

        int maxConn = CommonConfig.CONFIG.maxNodeConnections.get();

        // Use absolute positions unique to this test's structure placement
        BlockPos sourceAbs = helper.absolutePos(CENTER);
        handler.registerSource(sourceAbs, null, false);

        List<BlockPos> receiverPositions = new ArrayList<>();
        for (int i = 0; i < maxConn + 2; i++) {
            BlockPos pos = sourceAbs.offset(i + 1, 0, 0);
            handler.registerReceiver(pos, 10.0);
            receiverPositions.add(pos);
        }

        int successCount = 0;
        int failCount = 0;
        for (BlockPos receiverPos : receiverPositions) {
            if (handler.addLink(sourceAbs, receiverPos)) {
                successCount++;
            } else {
                failCount++;
            }
        }

        helper.assertTrue(successCount == maxConn,
                "Exactly maxNodeConnections=" + maxConn + " links must succeed, got " + successCount);
        helper.assertTrue(failCount >= 2,
                "At least 2 links past the limit must be rejected, got " + failCount);

        helper.succeed();
    }

    /**
     * Verifies that the {@code transmissionLossPerBlock} config produces the
     * mathematically correct attenuation: {@code starlight * (1-loss)^distance}.
     *
     * <p>This validates both the config range and the formula used in
     * {@code WorldNetworkHandler.distributeFromSource()}.</p>
     */
    @GameTest(template = PLATFORM)
    public void testTransmissionLossPerBlockFormula(GameTestHelper helper) {
        double lossPerBlock = CommonConfig.CONFIG.transmissionLossPerBlock.get();

        // Config is in valid range
        helper.assertTrue(lossPerBlock >= 0.0,
                "transmissionLossPerBlock must be non-negative");
        helper.assertTrue(lossPerBlock <= 0.1,
                "transmissionLossPerBlock must not exceed 0.1");

        // Formula verification at 10 blocks with the configured value
        double survivingFraction = Math.pow(1.0 - lossPerBlock, 10.0);
        helper.assertTrue(survivingFraction > 0.0,
                "Surviving fraction must be > 0 for any lossPerBlock < 1.0");
        helper.assertTrue(survivingFraction <= 1.0,
                "Surviving fraction must not exceed 1.0");

        if (lossPerBlock > 0.0) {
            helper.assertTrue(survivingFraction < 1.0,
                    "Positive lossPerBlock must produce < 1.0 surviving fraction over 10 blocks");
            // Default 0.005 over 64 blocks: (1-0.005)^64 ≈ 0.724 — more than half survives
            double survivalAt64 = Math.pow(1.0 - lossPerBlock, 64.0);
            helper.assertTrue(survivalAt64 > 0.5,
                    "Default lossPerBlock must leave > 50% starlight surviving over max link distance (64 blocks)");
        }

        helper.succeed();
    }

