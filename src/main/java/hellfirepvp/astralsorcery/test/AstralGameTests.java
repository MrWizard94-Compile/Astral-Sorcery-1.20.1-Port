    /**
     * Verifies that the {@code infusionCostMultiplier} config scales fluid cost
     * using {@code ceil(baseFluid * multiplier)} and that the formula produces
     * values consistent with the infuser's recipe-start logic.
     */
    @GameTest(template = PLATFORM)
    public void testInfusionCostMultiplierFormula(GameTestHelper helper) {
        double multiplier = CommonConfig.CONFIG.infusionCostMultiplier.get();
        boolean consumesLiquid = CommonConfig.CONFIG.infusionConsumesLiquid.get();

        // Multiplier must be positive (validated by config spec range 0.1–10.0)
        helper.assertTrue(multiplier > 0.0,
                "infusionCostMultiplier must be positive");

        // Formula: scaledRequired = ceil(baseFluid * multiplier)
        int baseFluid = 100; // example recipe fluid requirement (mB)
        int scaledRequired = (int) Math.ceil(baseFluid * multiplier);
        helper.assertTrue(scaledRequired >= 1,
                "Scaled fluid required must be at least 1 mB");

        if (multiplier > 1.0) {
            helper.assertTrue(scaledRequired > baseFluid,
                    "Multiplier > 1.0 must increase fluid requirement above base");
        } else if (multiplier < 1.0) {
            helper.assertTrue(scaledRequired <= baseFluid,
                    "Multiplier < 1.0 must not increase fluid requirement above base");
        } else {
            helper.assertTrue(scaledRequired == baseFluid,
                    "Multiplier = 1.0 must leave fluid requirement unchanged");
        }

        // infusionConsumesLiquid=false means the fluid remains in tank after craft
        // Both values are valid; confirm the boolean is accessible
        helper.assertTrue(consumesLiquid == Boolean.TRUE || consumesLiquid == Boolean.FALSE,
                "infusionConsumesLiquid must be a valid boolean");

        helper.succeed();
    }

