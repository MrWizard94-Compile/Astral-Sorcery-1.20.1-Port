    // Private helpers
    // ========================================================================

    @Nonnull
    private BlockEntityGateway requireGateway(@Nonnull GameTestHelper helper,
                                               @Nonnull BlockPos relPos) {
        BlockEntity be = helper.getBlockEntity(relPos);
        if (!(be instanceof BlockEntityGateway gateway)) {
            helper.fail("Expected BlockEntityGateway at " + relPos + ", found: " + be);
            throw new IllegalStateException("unreachable");
        }
        return gateway;
    }

    private static void assertNear(@Nonnull GameTestHelper helper,
                                    @Nonnull String label,
                                    double actual,
                                    double expected) {
        helper.assertTrue(Math.abs(actual - expected) < 0.001,
                label + ": expected " + expected + " but got " + actual);
    }

    private static void assertInRange(@Nonnull GameTestHelper helper,
                                       @Nonnull String name,
                                       int value, int min, int max) {
        helper.assertTrue(value >= min && value <= max,
                name + " must be in [" + min + ", " + max + "], got " + value);
    }

