    /**
     * End-to-end test of the gateway starlight cost path: places a gateway,
     * pre-fills its buffer to exactly the cost of a 50-block teleport, then
     * verifies {@code consumeStarlight()} succeeds and empties the buffer.
     */
    @GameTest(template = PLATFORM)
    public void testGatewayCostDeductedOnConsume(GameTestHelper helper) {
        helper.setBlock(CENTER, BlocksAS.GATEWAY.get().defaultBlockState());

        helper.runAfterDelay(2, () -> {
            BlockEntityGateway gateway = requireGateway(helper, CENTER);

            double costPerBlock = CommonConfig.CONFIG.gatewayCostPerBlock.get();
            double distance = 50.0; // simulate a 50-block same-dimension teleport
            double cost = distance * costPerBlock;

            if (cost <= 0.0) {
                // costPerBlock=0 means free teleports — nothing to test here
                helper.succeed();
                return;
            }

            // Give the gateway exactly the required cost
            gateway.receiveStarlight(cost, null);
            assertNear(helper, "buffer pre-consume", gateway.getStarlightBuffer(), cost);

            // Consume — should succeed exactly
            boolean ok = gateway.consumeStarlight(cost);
            helper.assertTrue(ok,
                    "consumeStarlight must succeed when buffer equals exact cost");
            assertNear(helper, "buffer after consuming full cost",
                    gateway.getStarlightBuffer(), 0.0);

            // Second consume — must now fail (buffer is 0)
            boolean denied = gateway.consumeStarlight(cost);
            helper.assertTrue(!denied,
                    "consumeStarlight must fail when buffer is empty");

            helper.succeed();
        });
    }

