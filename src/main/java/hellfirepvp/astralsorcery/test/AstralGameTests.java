    /**
     * Tests the full starlight buffer cycle on a live BlockEntityGateway:
     * receive → verify accumulation → consume success → verify deduction →
     * consume failure → verify buffer unchanged.
     *
     * <p>Covers: {@code gatewayCostPerBlock} consumer path, buffer bounds.</p>
     */
    @GameTest(template = PLATFORM)
    public void testGatewayStarlightBufferCycle(GameTestHelper helper) {
        helper.setBlock(CENTER, BlocksAS.GATEWAY.get().defaultBlockState());

        helper.runAfterDelay(2, () -> {
            BlockEntityGateway gateway = requireGateway(helper, CENTER);

            // Initial state
            helper.assertTrue(gateway.getStarlightBuffer() == 0.0,
                    "Gateway starlightBuffer must start at 0");

            // Receive — additive accumulation
            gateway.receiveStarlight(500.0, null);
            assertNear(helper, "buffer after 500 receive",
                    gateway.getStarlightBuffer(), 500.0);

            gateway.receiveStarlight(300.0, null);
            assertNear(helper, "buffer after +300 receive",
                    gateway.getStarlightBuffer(), 800.0);

            // Successful consumption
            boolean ok = gateway.consumeStarlight(200.0);
            helper.assertTrue(ok,
                    "consumeStarlight(200) must return true when buffer=800");
            assertNear(helper, "buffer after consuming 200",
                    gateway.getStarlightBuffer(), 600.0);

            // Insufficient consumption — buffer must be unchanged
            boolean denied = gateway.consumeStarlight(700.0);
            helper.assertTrue(!denied,
                    "consumeStarlight(700) must return false when buffer=600");
            assertNear(helper, "buffer unchanged after failed consume",
                    gateway.getStarlightBuffer(), 600.0);

            helper.succeed();
        });
    }

